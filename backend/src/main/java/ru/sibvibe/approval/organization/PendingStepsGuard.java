package ru.sibvibe.approval.organization;

import java.util.Collection;

/**
 * Что делать с документами, где человек — согласующий, когда его исключают из компании или снимают роль.
 *
 * Раньше такое действие запрещалось, пока у человека есть незавершённые шаги (иначе документ завис бы
 * навсегда). На приёмке 24.09 (п. 15) это оказалось тупиком для администратора: чтобы исключить сотрудника,
 * приходилось ждать, пока он сам согласует. Теперь действие выполняется сразу, а такие документы
 * возвращаются авторам: автор отправляет заново, маршрут подбирает другого носителя роли, а одобрения
 * остальных сохраняются, если документ не менялся.
 *
 * Реализует approval, потому что organization не вправе вызывать approval (ARCHITECTURE.md, раздел 2).
 * Вызывается в транзакции того, кто исключает, — под той же блокировкой участника.
 */
public interface PendingStepsGuard {

    /**
     * Возвращает авторам документы компании {@code orgId}, где {@code userId} ещё не решил.
     *
     * @param roleIds {@code null} — во всех ролях (исключение из компании), иначе — только в этих (снятые роли)
     * @return сколько документов вернулось авторам
     */
    int releaseSteps(long orgId, long userId, Collection<Long> roleIds);
}
