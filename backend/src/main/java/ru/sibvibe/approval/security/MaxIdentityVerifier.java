package ru.sibvibe.approval.security;

import java.util.Optional;

/**
 * Проверка подлинности личности пользователя, пришедшей из мини-приложения.
 *
 * ЭТО САМОЕ ВАЖНОЕ МЕСТО ВО ВСЕЙ БЕЗОПАСНОСТИ ПРОЕКТА.
 *
 * MAX Bridge отдаёт фронтенду данные запуска с подписью. Фронтенд - это браузер
 * пользователя, и всё, что он присылает, можно подделать. Если бэкенд поверит
 * идентификатору пользователя из тела запроса без проверки подписи, то любой
 * сможет действовать от имени директора, и вся ролевая модель становится
 * декорацией.
 *
 * Поэтому: идентификатор пользователя берётся ТОЛЬКО из проверенных данных
 * запуска и НИКОГДА из параметров запроса или тела.
 *
 * Подпись проверяется секретом бота. Дополнительно проверяется давность выдачи,
 * иначе однажды перехваченные данные работают вечно.
 */
public interface MaxIdentityVerifier {

    /**
     * @param rawInitData строка данных запуска, как её отдал MAX Bridge
     * @return личность, если подпись верна и данные не просрочены; иначе пусто
     */
    Optional<VerifiedIdentity> verify(String rawInitData);

    /**
     * @param maxUserId идентификатор пользователя в MAX - единственный доверенный
     *                  ключ для поиска сотрудника в нашей базе
     */
    record VerifiedIdentity(String maxUserId, String displayName, long issuedAtEpochSeconds) {}
}
